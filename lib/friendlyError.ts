/**
 * Преобразует ошибку RPC/БД в человекочитаемую фразу для пользователя.
 *
 * Правила:
 *  • известные ситуации (гонки, нехватка баланса) → понятная фраза;
 *  • остальные русские RAISE-сообщения (их пишет наш код) показываем как есть;
 *  • технические/английские ошибки Postgres (constraint, null value, и т.п.)
 *    наружу НЕ показываем — отдаём обобщённый fallback.
 */
export function friendlyDbError(
  raw: string | null | undefined,
  fallback = 'Что-то пошло не так. Попробуй ещё раз.',
): string {
  const m = (raw || '').trim();
  if (!m) return fallback;

  const known: Array<[RegExp, string]> = [
    [/уже (обработан|подтвержд|выдан|отмен|использован)/i, 'Эта заявка уже обработана'],
    [/(подтверждение|заявка|заказ).{0,20}не найден/i, 'Заявка не найдена или уже обработана'],
    [/недостаточно|не хватает/i, 'Недостаточно монет на балансе'],
    [/требует фото/i, 'Нужно приложить фото-доказательство'],
    [/чужая семья|нет доступа|доступ запрещ/i, 'Нет доступа'],
  ];
  for (const [re, msg] of known) if (re.test(m)) return msg;

  // Информативные русские сообщения (например, «Сумма должна быть от 0 до 50»)
  // оставляем как есть; чисто английские/технические — прячем за fallback.
  const hasCyrillic = /[А-Яа-я]/.test(m);
  return hasCyrillic ? m : fallback;
}
