-- 020 · tasks.remind_at — время напоминания ребёнку
--
-- NULL = без напоминания (по умолчанию).
-- TIME без timezone — хранится в московском времени (UTC+3).
-- Cron-job каждые 30 минут ищет задачи с remind_at = текущее время
-- и отправляет push-уведомления детям, не выполнившим задачу сегодня.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE public.tasks ADD COLUMN remind_at time DEFAULT NULL;

COMMENT ON COLUMN public.tasks.remind_at
  IS 'Время напоминания (MSK, UTC+3). NULL = не напоминать.';
